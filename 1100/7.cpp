bool possibility(int h,vector<int>&v,int x){
    int need=0;
    for(auto it:v) {need+=max(0LL,(h-it));}
    return (need<=x);
}
void solve() {
    // write your solution here
    int n,x;
    cin>>n>>x;
    vector<int>v(n);
    for(int i=0;i<n;i++){
        cin>>v[i];
    }
    int i=1,j=1e12,ans=-1;
    while(i<=j){
        int mid=i+(j-i)/2;
        if((possibility(mid,v,x))){
            ans=mid;
            i=mid+1;
        }
        else{
            j=mid-1;
        }
    }
    cout<<ans<<endl;
}

