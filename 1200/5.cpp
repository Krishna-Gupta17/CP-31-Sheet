void solve() {
    // write your solution here
    int n,k;cin>>n>>k;
    vector<vector<int>>v(k+1);
    for(int i=1;i<=k;i++) v[i].push_back(-1);
    for(int i=0;i<n;i++){
        int x;cin>>x;
        v[x].push_back(i);
    }
    for(int i=1;i<=k;i++) v[i].push_back(n);
    int ans=n;
    for(int i=1;i<=k;i++){
        int m=0,sm=0;
        auto &pos=v[i];
        for(int j=1;j<pos.size();j++){
            int g=pos[j]-pos[j-1]-1;
            if(g>m){
                sm=m;
                m=g;
            }
            else if(g>sm){
                sm=g;
            }
        }
        if(m/2>sm) ans=min(ans,m/2);
        else ans=min(ans,sm);
    }
    cout<<ans<<endl;
}

signed main() {
    ios::sync_with_stdio(false);
    cin.tie(NULL);

    int tc;
    cin >> tc;
    while (tc--) {
        solve();
    }
    return 0;
}